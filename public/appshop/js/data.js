// 평가 배정 — 조마다 다른 미션의 앱 두 개. 앱마다 정확히 두 조가 평가하게 된다.
export function targetsOf(team) {
  const t = Number(team), n = TEAM_COUNT;
  return [((t - 1 + 2) % n) + 1, ((t - 1 + 4) % n) + 1];
}

